N_AIE_ROWS = 4
HERE = Path(__file__).resolve().parent


def _walk(tap):
    """Flat source indices in stream order for a TensorAccessPattern."""
    order = []

    def rec(level, base):
        if level == len(tap.sizes):
            order.append(base)
            return
        for i in range(tap.sizes[level]):
            rec(level + 1, base + i * tap.strides[level])

    rec(0, tap.offset)
    return np.array(order)


def _bias_kernels(m, k, n, dims):
    """Generate conv_bias_layout.h for this tile config and return (unpack, fill) kernels."""
    order_c = _walk(dims.C)  # L1 position order_c[j] holds row-major element j of the m x n tile
    inv = np.empty_like(order_c)
    inv[order_c] = np.arange(len(order_c))
    rows = inv // n  # row of each L1 position
    group = 8
    assert len(rows) == m * n and all(len(set(rows[g : g + group])) == 1 for g in range(0, m * n, group))
    row_of_group = rows[::group]
    order_a = _walk(dims.A)
    hdr = HERE / "build" / f"conv_bias_layout_m{m}k{k}n{n}.h"
    hdr.parent.mkdir(exist_ok=True)
    hdr.write_text(
        "// generated by conv1d_npu.py\n#include <stdint.h>\n"
        f"#define CB_M {m}\n#define CB_ELEMS {m * n}\n#define CB_GROUP {group}\n"
        "static const uint16_t CB_ROW_OF_GROUP[] = {" + ",".join(str(int(r)) for r in row_of_group) + "};\n"
        "// A stream order (L1 position -> flat m x k index), for host-side bias packing:\n"
        "// " + " ".join(str(int(v)) for v in order_a[: 2 * m]) + "\n"
    )
    inc = [str(hdr.parent)]
    flags = [f"-include{hdr}"]
    a_ty = np.ndarray[(m * k,), np.dtype[bfloat16]]
    c_ty = np.ndarray[(m * n,), np.dtype[np.float32]]
    b_ty = np.ndarray[(m,), np.dtype[np.float32]]
    unpack = ExternalFunction("conv_bias_unpack", source_file=str(HERE / "conv_bias_unpack.cc"), arg_types=[a_ty, b_ty], include_dirs=inc, compile_flags=flags)
    fill = ExternalFunction("conv_bias_fill", source_file=str(HERE / "conv_bias_fill.cc"), arg_types=[c_ty, b_ty], include_dirs=inc, compile_flags=flags)
    return unpack, fill


@iron.jit
def conv1d(
    A: In,
    B: In,
    C: Out,
    D: In,  # bias objects: per core row one A-shaped object [m*k] bf16 (see conv_bias.cc)
    *,
    M: DispatchTime[np.int32],  # Cout
    Cin2: DispatchTime[np.int32],  # rows of Z = 2 * cin_pad (multiple of k, <= 1023)
    taps2: DispatchTime[np.int32],  # super-taps = ceil(taps / 2)
    tstride: DispatchTime[np.int32],  # element stride between super-taps (= 2*dil, even)
    N: DispatchTime[np.int32],  # output frames (padded to a multiple of n*cols)
    ldx: DispatchTime[np.int32],  # row stride of Z (even)
    nc: DispatchTime[np.int32],  # column tiles per shim column per DMA chunk (<= 64)
    m: CompileTime[int],
    k: CompileTime[int],
    n: CompileTime[int],
    n_aie_cols: CompileTime[int],
    c_depth: CompileTime[int] = 2,
):
    n_aie_rows = N_AIE_ROWS
    n_aie_cores = n_aie_rows * n_aie_cols
    fifo_depth = 2
    n_shim_mem_A = min(n_aie_rows, n_aie_cols)
    n_A_tiles_per_shim = max(1, n_aie_rows // n_aie_cols)

    dtype_in = np_ndarray_type_get_dtype(A)
    dtype_out = np_ndarray_type_get_dtype(C)

    matmul_kernel = kernels.mm(
        dim_m=m, dim_k=k, dim_n=n, input_dtype=dtype_in, output_dtype=dtype_out
    )
    dims = matmul_kernel.stream_dims
    bias_unpack, bias_fill = _bias_kernels(m, k, n, dims)

    dev = iron.get_current_device()
    assert dev is not None
    if n_aie_cols > dev.cols:
        raise ValueError(f"n_aie_cols={n_aie_cols} but the device has {dev.cols} columns")

    A_l2_ty = np.ndarray[(m * k * n_A_tiles_per_shim,), np.dtype[dtype_in]]
    B_l2_ty = np.ndarray[(k * n,), np.dtype[dtype_in]]
    C_l2_ty = np.ndarray[(m * n * n_aie_rows,), np.dtype[dtype_out]]
    A_l1_ty = np.ndarray[(m, k), np.dtype[dtype_in]]
    B_l1_ty = np.ndarray[(k, n), np.dtype[dtype_in]]
    C_l1_ty = np.ndarray[(m, n), np.dtype[dtype_out]]
    rtp_ty = np.ndarray[(4,), np.dtype[np.int32]]
    bias_ty = np.ndarray[(m,), np.dtype[np.float32]]

    A_l3l2_fifos: list[ObjectFifo] = []
    A_l2l1_fifos: list[ObjectFifo] = []
    B_l3l2_fifos: list[ObjectFifo] = []
    B_l2l1_fifos: list[ObjectFifo] = []
    C_l1l2_fifos: list[list[ObjectFifo]] = [[] for _ in range(n_aie_rows)]
    C_l2l3_fifos: list[ObjectFifo] = []

    for i in range(n_shim_mem_A):
        a_l3l2 = ObjectFifo(A_l2_ty, name=f"A_L3L2_{i}", depth=fifo_depth)
        A_l3l2_fifos.append(a_l3l2)
        start_row = i * n_A_tiles_per_shim
        stop_row = start_row + n_A_tiles_per_shim
        A_l2l1_fifos.extend(
            a_l3l2.cons().split(
                [m * k * j for j in range(stop_row - start_row)],
                obj_types=[A_l1_ty] * (stop_row - start_row),
                names=[f"A_L2L1_{row}" for row in range(start_row, stop_row)],
                to_stream=[dims.A] * (stop_row - start_row),
            )
        )

    for col in range(n_aie_cols):
        b_l3l2 = ObjectFifo(B_l2_ty, name=f"B_L3L2_{col}", depth=fifo_depth)
        B_l3l2_fifos.append(b_l3l2)
        B_l2l1_fifos.append(
            b_l3l2.cons().forward(obj_type=B_l1_ty, name=f"B_L2L1_{col}", to_stream=dims.B)
        )
        c_l2l3 = ObjectFifo(C_l2_ty, name=f"C_L2L3_{col}", depth=fifo_depth, to_stream=dims.C)
        C_l2l3_fifos.append(c_l2l3)
        c_tmp_fifos = c_l2l3.prod().join(
            [m * n * i for i in range(n_aie_rows)],
            obj_types=[C_l1_ty] * n_aie_rows,
            names=[f"C_L1L2_{col}_{row}" for row in range(n_aie_rows)],
            depths=[c_depth] * n_aie_rows,
        )
        for j in range(n_aie_rows):
            C_l1l2_fifos[j].append(c_tmp_fifos[j])

    rtps = [
        [Buffer(rtp_ty, name=f"rtp_{row}_{col}", use_write_rtp=True) for col in range(n_aie_cols)]
        for row in range(n_aie_rows)
    ]
    bias_bufs = [[Buffer(bias_ty, name=f"bias_{row}_{col}") for col in range(n_aie_cols)] for row in range(n_aie_rows)]
    barriers = [[WorkerRuntimeBarrier() for _ in range(n_aie_cols)] for _ in range(n_aie_rows)]

    def core_fn(in_a, in_b, out_c, f_unpack, f_fill, matmul, rtp, bias, barrier):
        barrier.wait_for_value(1)
        k_iters = rtp[0]
        nc_tiles = rtp[1]
        n_chunks = rtp[2]
        barrier.release_with_value(1)
        for _ in range_(n_chunks):
            # every chunk starts with one bias object on the A fifo
            bobj = in_a.acquire(1)
            f_unpack(bobj, bias)
            in_a.release(1)
            for _ in range_(nc_tiles):
                elem_out = out_c.acquire(1)
                f_fill(elem_out, bias)
                for _ in range_(k_iters):
                    elem_in_a = in_a.acquire(1)
                    elem_in_b = in_b.acquire(1)
                    matmul(elem_in_a, elem_in_b, elem_out)
                    in_a.release(1)
                    in_b.release(1)
                out_c.release(1)

    workers = Worker.grid(
        n_aie_rows,
        n_aie_cols,
        lambda row, col: Worker(
            core_fn,
            [
                A_l2l1_fifos[row].cons(),
                B_l2l1_fifos[col].cons(),
                C_l1l2_fifos[row][col].prod(),
                bias_unpack,
                bias_fill,
                matmul_kernel,
                rtps[row][col],
                bias_bufs[row][col],
                barriers[row][col],
            ],
            stack_size=0xD00,
        ),
    )
    flat_workers = [w for row in workers for w in row]

    A_prods = [f.prod() for f in A_l3l2_fifos]
    B_prods = [f.prod() for f in B_l3l2_fifos]
    C_conses = [f.cons() for f in C_l2l3_fifos]

    def sequence(A, B, C, D, M, Cin2, taps2, tstride, N, ldx, nc, A_hs, B_hs, C_hs):
        K = taps2 * Cin2
        require(M > 0, "M must be positive")
        require(Cin2 > 0, "Cin2 must be positive")
        require(taps2 > 0, "taps2 must be positive")
        require(tstride > 0, "tstride must be positive")
        require(tstride % 2 == 0, "tstride must be even")
        require(ldx % 2 == 0, "ldx must be even")
        require(N > 0, "N must be positive")
        require(M % (m * n_aie_rows) == 0, "M must be a multiple of m * n_aie_rows")
        require(Cin2 % k == 0, "Cin2 must be a multiple of k")
        require(N % (n * n_aie_cols) == 0, "N must be a multiple of n * n_aie_cols")
        require(nc > 0, "nc must be positive")
        require(nc <= 64, "nc must be <= 64 (shim DMA iteration limit)")
        require((N // n // n_aie_cols) % nc == 0, "column tiles per column must be a multiple of nc")

        n_row_blocks = M // m // n_aie_rows
        n_chunks = N // n // n_aie_cols // nc
        for row in range(n_aie_rows):
            for col in range(n_aie_cols):
                rtps[row][col][0] = K // k
                rtps[row][col][1] = nc
                rtps[row][col][2] = n_row_blocks * n_chunks
                barriers[row][col].set(1)

        chunk_elems = nc * n * n_aie_cols  # output columns per chunk

        for step, tg in TaskGroup.pipelined(n_row_blocks * n_chunks, depth=3):
            row = step // n_chunks
            ch = step % n_chunks
            for col in range(n_aie_cols):
                # C[row block, columns of this shim column within the chunk]
                c_tap = TensorAccessPattern(
                    (M * N,),
                    row * (m * n_aie_rows) * N + ch * chunk_elems + col * n,
                    [nc, m * n_aie_rows, n],
                    [n * n_aie_cols, N, 1],
                )
                C_hs[col].drain(C, tap=c_tap, wait=True, group=tg)
                if col < n_shim_mem_A:
                    # bias object for core row (row * n_shim_mem_A + col): D[(row block, core row)]
                    d_tap = TensorAccessPattern(
                        (M // m * m * k,),
                        (row * n_shim_mem_A + col) * m * k,
                        [1, m * k],
                        [m * k, 1],
                    )
                    A_hs[col].fill(D, tap=d_tap, group=tg)
                    # A row-of-tiles (row * n_shim_mem_A + col), repeated nc times.
                    a_tap = TensorAccessPattern(
                        (M * K,),
                        (row * n_shim_mem_A + col) * m * K,
                        [nc, K // k, m, k],
                        [0, k, K, 1],
                    )
                    A_hs[col].fill(A, tap=a_tap, group=tg)
                # Virtual im2col walk over Z (row stride ldx): [n-tile, super-tap, row, t].
                b_tap = TensorAccessPattern(
                    (Cin2 * ldx,),
                    ch * chunk_elems + col * n,
                    [nc, taps2, Cin2, n],
                    [n * n_aie_cols, tstride, ldx, 1],
                )
                B_hs[col].fill(B, tap=b_tap, group=tg)

    rt = Runtime(sequence, [A, B, C, D, M, Cin2, taps2, tstride, N, ldx, nc, A_prods, B_prods, C_conses])
    return Program(dev, rt, workers=flat_workers).resolve_program()


def _make_argparser():
    p = argparse.ArgumentParser(prog="NPU conv1d (DMA im2col matmul)")
    add_compile_args(p, short_dev=None)
    p.add_argument("-m", type=int, default=32)
    p.add_argument("-k", type=int, default=64)
    p.add_argument("-n", type=int, default=32)
    p.add_argument("--n-aie-cols", type=int, choices=[1, 2, 4, 8], default=4)
    p.add_argument("--c-depth", type=int, default=2, help="core-side C tile buffers (1 saves L1 for wider n)")
    p.add_argument("--a-elems", type=int, default=4 * 1024 * 1024, help="Wmat buffer (bf16 elems)")
    p.add_argument("--b-elems", type=int, default=32 * 1024 * 1024, help="Xp buffer (bf16 elems)")
    p.add_argument("--c-elems", type=int, default=32 * 1024 * 1024, help="Y buffer (f32 elems)")
    return p


def _compile_kwargs(opts):
    return dict(
        A=np.ndarray[(opts.a_elems,), np.dtype[bfloat16]],
        B=np.ndarray[(opts.b_elems,), np.dtype[bfloat16]],
        C=np.ndarray[(opts.c_elems,), np.dtype[np.float32]],
        D=np.ndarray[(64 * opts.m * opts.k,), np.dtype[bfloat16]],
        m=opts.m,
        k=opts.k,
        n=opts.n,
        n_aie_cols=opts.n_aie_cols,
        c_depth=opts.c_depth,
    )


def main():
    opts = _make_argparser().parse_args()
    run_design_cli(
        conv1d,
        opts,
        compile_kwargs=_compile_kwargs,
        device=lambda o: from_name(o.dev, n_cols=o.n_aie_cols if o.dev == "npu" else None),
    )


if __name__ == "__main__":
    main()
