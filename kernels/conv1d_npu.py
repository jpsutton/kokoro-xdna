"""1-D convolution (NCW, stride 1, group 1) as a matmul with DMA-side im2col.

    Y[co, t] = sum_{j, ci} W[co, ci, j] * Xp[ci, t + j*dil]

Shim DMA offsets/strides must be whole 4-byte words, so a bf16 stream cannot
be shifted by an odd element count (every Kokoro dilation is odd). Taps are
therefore paired: the host builds Z with 2*Cin rows,

    Z[ci, t]       = Xp[ci, t]
    Z[Cin + ci, t] = Xp[ci, t + dil]

and the conv becomes taps2 = ceil(taps/2) "super-taps" of stride 2*dil over
Z, i.e. C = A @ B with

    A = Wmat  (M=Cout) x (K=taps2*Cin2)   A[co, i*Cin2 + ci]       = W[co, ci, 2i]
                                           A[co, i*Cin2 + Cin + ci] = W[co, ci, 2i+1]
    B[i*Cin2 + r, t] = Z[r, t + 2*i*dil]   (never materialised: one 4-D DMA
                                           walk [n-tile, super-tap, row, t])
    C = Y     (M)      x (N=T_out)

The compute tiles run the stock bf16 matmul microkernel; all shape values are
``DispatchTime`` so one xclbin serves every conv in the model.

All shape parameters are ``DispatchTime``: one xclbin per (m, k, n, cols)
tile config, instructions synthesised per call by the generated dispatch
library (``dispatch-*.so``) which plain ctypes can load at runtime.
"""

